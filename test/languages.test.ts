import { describe, expect, it } from 'vitest';
import { lockfiles } from '../src/rules/cc6.8/lockfiles.js';
import { dangerousExecution } from '../src/rules/cc6.6/dangerous-execution.js';
import { openAdminPorts } from '../src/rules/cc6.6/open-admin-ports.js';
import { sqlStringBuilding } from '../src/rules/cc6.6/sql-string-building.js';
import { tlsVerification } from '../src/rules/cc6.7/tls-verification.js';
import { weakTlsCrypto } from '../src/rules/cc6.7/weak-tls-crypto.js';
import { plainHttpUrls } from '../src/rules/cc6.7/plain-http-urls.js';
import { genericPassword } from '../src/rules/cc6.1/generic-password.js';
import { parseTerraform } from '../src/rules/lib/terraform.js';
import { run, titles } from './helpers/memory.js';

describe('Python and Go detection', () => {
  it('flags disabled TLS verification in Python and Go, but not in tests', async () => {
    const out = await run(tlsVerification, {
      'app/client.py': 'requests.get(url, verify=False)\n',
      'cmd/main.go': 'cfg := &tls.Config{InsecureSkipVerify: true}\n',
      'tests/test_client.py': 'requests.get(url, verify=False)\n',
    });
    expect(out.status === 'fail' && out.findings.map((f) => f.path)).toEqual([
      'app/client.py',
      'cmd/main.go',
    ]);
  });

  it('flags string-built SQL in Python f-strings, % formatting and Go Sprintf', async () => {
    const out = await run(sqlStringBuilding, {
      'app/a.py': 'cur.execute(f"SELECT * FROM users WHERE id = {uid}")\n',
      'app/b.py': 'cur.execute("SELECT * FROM users WHERE id = %s" % uid)\n',
      'app/ok.py': 'cur.execute("SELECT * FROM users WHERE id = %s", (uid,))\n',
      'db/q.go': 'q := fmt.Sprintf("SELECT * FROM users WHERE id = %s", id)\n',
    });
    expect(out.status === 'fail' && out.findings.map((f) => f.path)).toEqual([
      'app/a.py',
      'app/b.py',
      'db/q.go',
    ]);
  });

  it('ignores tagged SQL templates and UI copy', async () => {
    const out = await run(sqlStringBuilding, {
      'src/q.ts':
        'const rows = await sql`SELECT * FROM users WHERE id = ${id}`;\nconst msg = `Please select ${item} from the list`;\n',
    });
    expect(out.status).toBe('pass');
  });

  it('flags shell=True, os.system, pickle and unsafe yaml.load, not yaml.safe_load', async () => {
    const out = await run(dangerousExecution, {
      'app/run.py': [
        'subprocess.run(cmd, shell=True)',
        'os.system(cmd)',
        'data = pickle.loads(blob)',
        'cfg = yaml.load(text)',
        'cfg = yaml.load(text, Loader=yaml.SafeLoader)',
        'cfg = yaml.safe_load(text)',
        'redis.eval(script)',
      ].join('\n'),
    });
    expect(out.status === 'fail' && out.findings.map((f) => f.line)).toEqual([1, 2, 3, 4]);
  });

  it('flags weak TLS minimums and ciphers in Go and Python', async () => {
    const out = await run(weakTlsCrypto, {
      'tls.go': 'c := &tls.Config{MinVersion: tls.VersionTLS10}\nb, _ := des.NewCipher(k)\n',
      'enc.py': 'cipher = AES.new(key, AES.MODE_ECB)\n',
    });
    expect(titles(out)).toHaveLength(3);
  });

  it('honours a 1.3 minimum TLS policy from config', async () => {
    const files = { 'server.go': 'c := &tls.Config{MinVersion: tls.VersionTLS12}\n' };
    expect((await run(weakTlsCrypto, files)).status).toBe('pass');
    expect((await run(weakTlsCrypto, files, { thresholds: { minTlsVersion: '1.3' } })).status).toBe(
      'fail',
    );
  });

  it('skips generated files but still scans authored ones', async () => {
    const out = await run(tlsVerification, {
      'src/gen.ts':
        '// Code generated by protoc. DO NOT EDIT.\nconst o = { rejectUnauthorized: false };\n',
      'src/real.ts': 'const o = { rejectUnauthorized: false };\n',
    });
    expect(out.status === 'fail' && out.findings.map((f) => f.path)).toEqual(['src/real.ts']);
  });

  it('reports not applicable, never pass, for unsupported languages', async () => {
    const out = await run(dangerousExecution, {
      'app/Main.java': 'Runtime.getRuntime().exec(cmd);\n',
    });
    expect(out.status).toBe('not_applicable');
  });
});

describe('heuristic rules stay quiet on common false positives', () => {
  it('plain HTTP: ignores localhost, schemas, examples and container hostnames', async () => {
    const out = await run(plainHttpUrls, {
      'src/a.ts': [
        "const a = 'http://localhost:3000';",
        "const b = 'http://www.w3.org/2000/svg';",
        "const c = 'http://api.example.com';",
        "const d = 'http://redis:6379';",
        "const e = 'http://169.254.169.254/latest/meta-data';",
      ].join('\n'),
    });
    expect(out.status).toBe('pass');
  });

  it('generic password: ignores env lookups, placeholders and field names', async () => {
    const out = await run(genericPassword, {
      'src/a.ts': [
        'const password = process.env.DB_PASSWORD;',
        "const passwordField = 'user_password_input';",
        "const apiKey = 'your-api-key-here';",
        "const secret = '${SECRET}';",
        "const label = { password: 'Password' };",
      ].join('\n'),
      'config/app.yml': 'db:\n  password: "${DB_PASSWORD}"\n',
      'playwright.config.ts': "env: { ADMIN_PASSWORD: 'Pl4ywright-only' }",
    });
    expect(out.status).toBe('pass');
  });
});

describe('infrastructure', () => {
  it('parses nested Terraform blocks, attributes and heredocs', () => {
    const [sg] = parseTerraform(
      `resource "aws_security_group" "db" {
  description = <<EOT
not { a block }
EOT
  ingress {
    from_port   = 0
    to_port     = 65535
    cidr_blocks = ["0.0.0.0/0"] # wide open
  }
}`,
      'main.tf',
    );
    expect(sg?.labels).toEqual(['aws_security_group', 'db']);
    expect(sg?.children.map((c) => [c.kind, c.line, c.attrs.to_port])).toEqual([
      ['ingress', 5, '65535'],
    ]);
  });

  it('flags GCP firewalls open to the world on admin ports', async () => {
    const out = await run(openAdminPorts, {
      'net.tf': `resource "google_compute_firewall" "ssh" {
  source_ranges = ["0.0.0.0/0"]
  allow {
    protocol = "tcp"
    ports    = ["22", "8000-9000"]
  }
}`,
    });
    expect(out.status === 'fail' && out.findings.map((f) => f.severity)).toEqual(['high']);
  });

  it('flags CloudFormation ingress from 0.0.0.0/0 to databases', async () => {
    const out = await run(openAdminPorts, {
      'stack.yaml': `Resources:
  Db:
    Type: AWS::EC2::SecurityGroup
    Properties:
      VpcId: !Ref Vpc
      SecurityGroupIngress:
        - IpProtocol: tcp
          FromPort: 5432
          ToPort: 5432
          CidrIp: 0.0.0.0/0`,
    });
    expect(out.status === 'fail' && out.findings[0]?.severity).toBe('critical');
  });
});

describe('lockfiles', () => {
  it('accepts a workspace root lockfile, and grades Python requirements', async () => {
    const out = await run(lockfiles, {
      'package.json': '{ "dependencies": { "a": "1" } }',
      'pnpm-lock.yaml': "lockfileVersion: '9.0'",
      'packages/web/package.json': '{ "dependencies": { "b": "1" } }',
      'svc/requirements.txt': 'flask\nrequests==2.32.3\n',
      'jobs/requirements.txt': 'requests==2.32.3\n',
    });
    expect(out.status === 'fail' && out.findings.map((f) => [f.path, f.severity])).toEqual([
      ['jobs/requirements.txt', 'low'],
      ['svc/requirements.txt', 'medium'],
    ]);
  });
});
