// Source-file classification shared by code rules.
import type { RepoFile } from '../../engine/types.js';

export type Language = 'js' | 'python' | 'go';

export const LANGUAGE_LABELS: Record<Language, string> = {
  js: 'JS/TS',
  python: 'Python',
  go: 'Go',
};

const EXTENSIONS: Record<Language, RegExp> = {
  js: /\.(?:[cm]?jsx?|tsx?|vue|svelte)$/,
  python: /\.py$/,
  go: /\.go$/,
};

const TEST_PATH =
  /(?:^|\/)(?:tests?|__tests__|__mocks__|specs?|testdata|fixtures?|e2e|cypress|playwright)\/|\.(?:test|spec)\.[cm]?[jt]sx?$|_test\.go$|(?:^|\/)test_[^/]*\.py$|_test\.py$|(?:^|\/)conftest\.py$|(?:^|\/)(?:playwright|vitest|jest|cypress|karma|wdio)\.conf(?:ig)?\.[cm]?[jt]s$/;

const VENDORED =
  /(?:(?:^|\/)(?:vendor|third_party|node_modules|dist|build|\.next|out)\/)|(?:\.min\.js$)/;

export function languageOf(path: string): Language | undefined {
  for (const [lang, re] of Object.entries(EXTENSIONS) as [Language, RegExp][]) {
    if (re.test(path)) return lang;
  }
  return undefined;
}

export function isTestPath(path: string): boolean {
  return TEST_PATH.test(path);
}

export function isVendored(path: string): boolean {
  return VENDORED.test(path);
}

/** Production source files: supported language, not tests, not vendored or built output. */
export function isProductionSource(f: RepoFile, languages?: readonly Language[]): boolean {
  const lang = languageOf(f.path);
  if (!lang || (languages && !languages.includes(lang))) return false;
  return !isTestPath(f.path) && !isVendored(f.path);
}

/** Generated files are data, not authored code (Go's "Code generated ... DO NOT EDIT" convention and friends). */
export function isGenerated(text: string): boolean {
  return /@generated\b|\bGENERATED by\b|\bDO NOT EDIT\b/.test(text.slice(0, 500));
}

/** True when a line is (most likely) a comment; used to skip matches in commentary. */
export function isCommentLine(line: string): boolean {
  return /^\s*(?:\/\/|#|\*|\/\*|<!--|--)/.test(line);
}
