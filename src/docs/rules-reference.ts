// Renders docs/site/rules.md from the rule registry and the rubric.
// Regenerate with `pnpm gen:docs`; test/docs.test.ts fails if it drifts.
import { CRITERIA } from '../engine/criteria.generated.js';
import { CATEGORY_LABELS, CATEGORIES } from '../engine/types.js';
import { RULES } from '../rules/index.js';

const cell = (s: string) => s.replace(/\|/g, '\\|');

export function renderRulesReference(): string {
  const out = [
    '# Rule reference',
    '',
    `threesock ships ${RULES.length} built-in rules. External scanners add checks of their own when installed ([tools](tools.md)). Criteria without a rule here are scored MANUAL, with guidance on the evidence to gather.`,
    '',
    "Run `threesock explain <criterion>` for a criterion's full requirement, checks and red flags.",
    '',
    '<!-- Generated by `pnpm gen:docs` from src/rules. Do not edit by hand. -->',
  ];
  for (const category of CATEGORIES) {
    out.push('', `## ${CATEGORY_LABELS[category]}`, '');
    for (const def of CRITERIA.filter((c) => c.category === category)) {
      const rules = RULES.filter((r) => r.criterion === def.id);
      out.push(`### ${def.id} · ${def.title}`, '');
      if (rules.length === 0) {
        out.push(
          def.defaultManual
            ? 'MANUAL by rubric default: evidenced outside the repository.'
            : 'No automated rules yet: scored MANUAL.',
          '',
        );
        continue;
      }
      out.push('| Rule | Checks that | Default severity | Notes |', '|---|---|---|---|');
      for (const r of rules) {
        const notes = [
          r.redFlag === true && 'rubric red flag',
          r.requires?.includes('github') && 'needs `--github`',
        ]
          .filter(Boolean)
          .join(', ');
        out.push(`| \`${r.id}\` | ${cell(r.title)} | ${r.severity} | ${notes} |`);
      }
      out.push('');
    }
  }
  return `${out.join('\n').replace(/\n{3,}/g, '\n\n')}\n`;
}
