#!/usr/bin/env node
// Regenerates src/rules/index.ts from the rule files under src/rules/<criterion>/.
// Usage: node scripts/gen-rule-index.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const base = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'rules');
const FAMILY = { cc: 0, a: 1, pi: 2, c: 3, p: 4 };
const key = (dir) => [FAMILY[/^[a-z]+/.exec(dir)[0]], ...dir.match(/\d+/g).map(Number)];
const byCriterion = (a, b) => {
  const [x, y] = [key(a), key(b)];
  for (let i = 0; i < x.length; i++) if (x[i] !== y[i]) return x[i] - y[i];
  return 0;
};

const dirs = readdirSync(base)
  .filter((d) => /^[a-z]+\d+\.\d+$/.test(d))
  .sort(byCriterion);
const imports = [];
const entries = [];
for (const dir of dirs) {
  entries.push(`  // ${dir.toUpperCase()}`);
  for (const file of readdirSync(join(base, dir))
    .filter((f) => f.endsWith('.ts'))
    .sort()) {
    const src = readFileSync(join(base, dir, file), 'utf8');
    const names = [
      ...src.matchAll(/^export const (\w+) = [a-zA-Z]+Rule\(|^export const (\w+): Rule = \{/gm),
    ].map((m) => m[1] ?? m[2]);
    if (names.length !== 1)
      throw new Error(`${dir}/${file}: expected exactly one exported rule, found ${names.length}`);
    imports.push(`import { ${names[0]} } from './${dir}/${file.slice(0, -3)}.js';`);
    entries.push(`  ${names[0]},`);
  }
}

writeFileSync(
  join(base, 'index.ts'),
  [
    '// Rule registry, ordered by criterion. Generated by scripts/gen-rule-index.mjs',
    '// (`pnpm gen:rules`); test/criteria.test.ts fails if a rule file is missing.',
    "import type { Rule } from '../engine/types.js';",
    ...imports,
    '',
    'export const RULES: readonly Rule[] = [',
    ...entries,
    '];',
    '',
  ].join('\n'),
);
console.log(`Registered ${imports.length} rules.`);
